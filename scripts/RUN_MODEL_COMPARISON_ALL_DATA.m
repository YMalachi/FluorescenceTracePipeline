function dataset_id = parse_dataset_id(dataset_name)
% parse_dataset_id
%
% Extracts dataset number from names like:
%   data.1.train.preprocessed.mat

    tokens = regexp(dataset_name, 'data\.(\d+)\.train', 'tokens');

    if isempty(tokens)
        dataset_id = NaN;
    else
        dataset_id = str2double(tokens{1}{1});
    end
end

function summary_table = summarize_results_table(detailed_results)
% summarize_results_table
%
% Aggregates detailed results across neurons/recordings.
%
% Grouping:
%   model x target_fps x evaluation_mode
%
% Only rows with status == "ok" are included.

    ok_rows = detailed_results(detailed_results.status == "ok", :);

    if isempty(ok_rows)
        warning('No successful result rows found. Summary table will be empty.');
        summary_table = table();
        return;
    end

    group_vars = {'model', 'target_fps', 'evaluation_mode'};

    [G, group_model, group_fps, group_mode] = findgroups( ...
        ok_rows.model, ...
        ok_rows.target_fps, ...
        ok_rows.evaluation_mode);

    n_groups = max(G);

    summary_table = table();

    for g = 1:n_groups

        idx = G == g;
        group_data = ok_rows(idx, :);

        n_rows = height(group_data);
        n_unique_recordings = height(unique(group_data(:, {'dataset_id', 'recording_idx'})));

        F1_values = group_data.F1;
        precision_values = group_data.precision;
        recall_values = group_data.recall;
        median_abs_timing_values = group_data.median_abs_timing_error_sec;
        mean_signed_timing_values = group_data.mean_signed_timing_error_sec;
        timing_weighted_recall_values = group_data.timing_weighted_recall;

        row = table( ...
            group_model(g), ...
            group_fps(g), ...
            group_mode(g), ...
            n_rows, ...
            n_unique_recordings, ...
            mean(F1_values, 'omitnan'), ...
            median(F1_values, 'omitnan'), ...
            std(F1_values, 'omitnan'), ...
            std(F1_values, 'omitnan') / sqrt(sum(~isnan(F1_values))), ...
            mean(precision_values, 'omitnan'), ...
            median(precision_values, 'omitnan'), ...
            mean(recall_values, 'omitnan'), ...
            median(recall_values, 'omitnan'), ...
            mean(median_abs_timing_values, 'omitnan'), ...
            median(median_abs_timing_values, 'omitnan'), ...
            mean(mean_signed_timing_values, 'omitnan'), ...
            median(mean_signed_timing_values, 'omitnan'), ...
            mean(timing_weighted_recall_values, 'omitnan'), ...
            median(timing_weighted_recall_values, 'omitnan'), ...
            'VariableNames', { ...
                'model', ...
                'target_fps', ...
                'evaluation_mode', ...
                'n_result_rows', ...
                'n_unique_recordings', ...
                'mean_F1', ...
                'median_F1', ...
                'std_F1', ...
                'sem_F1', ...
                'mean_precision', ...
                'median_precision', ...
                'mean_recall', ...
                'median_recall', ...
                'mean_median_abs_timing_error_sec', ...
                'median_median_abs_timing_error_sec', ...
                'mean_signed_timing_error_sec', ...
                'median_signed_timing_error_sec', ...
                'mean_timing_weighted_recall', ...
                'median_timing_weighted_recall'});

        summary_table = [summary_table; row];
    end
end